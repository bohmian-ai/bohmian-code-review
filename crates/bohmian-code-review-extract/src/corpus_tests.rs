//! Per-language normalized differential corpus tests.
//!
//! Each native language's fixture source is extracted by
//! [`Extractor::extract`] and compared against a frozen normalized golden
//! captured from the pinned upstream oracle (the wasm extractor at
//! `572d22bf`, run with `CODEGRAPH_KERNEL=0`). The corpus manifest
//! (`tools/oracle/fixtures/manifest.json`) marks each fixture `match`
//! (native output must equal the golden) or `defer` (the parse tree
//! contains errors; native extraction must return
//! [`ExtractionError::Deferred`] and the golden records the oracle's
//! recovered extraction — the skipped/deferred distinction).
//!
//! The corpus covers all 31 native languages: the frozen kernel's original
//! 20 plus the five systems/configuration grammar ports (Objective-C,
//! Solidity, Terraform, ArkTS, and Nix) and the six enterprise/legacy
//! grammar ports (Pascal, CFScript, CFQuery, COBOL, VB.NET, Erlang), plus
//! the composite/Twig routes (Svelte, Vue, Astro, Liquid, Razor, YAML,
//! Twig, XML/properties, CFML, DFM/FMX, Play routes, Erlang app files). The
//! `systems_config_*` tests are the focused differential for those five
//! (selected by `mise run test:extract -- systems_config`), the
//! `enterprise_*` tests are the focused differential for the six enterprise
//! ports (selected by `mise run test:extract -- enterprise`), and the
//! `composite_*` tests are the focused differential for the composite
//! routes (selected by `mise run test:extract -- composite`).
//!
//! Golden files live under `tools/oracle/goldens/` and are generated by
//! `tools/oracle/run-oracle.mjs`; the differential test is the fast-lane
//! check that the native extractor reproduces the oracle exactly.

use crate::config::ExtractionConfig;
