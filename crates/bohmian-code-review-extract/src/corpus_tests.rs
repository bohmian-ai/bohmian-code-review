#[test]
/// Verifies that composite matrix is exhaustive preserves the frozen extraction contract.
///
/// The composite corpus must include: every special route with no
/// false-positive neighbors; empty templates retaining file facts; Shopify
/// template/section paths (with nested templates) routing while
/// `config/`/`locales/` JSON does not; generic XML emitting only the file
/// node; MyBatis mapper + iBatis sqlMap shapes; `.src` alone not being an
/// Erlang app; CRLF and multibyte coordinate content; and malformed
/// delimiters.
///
/// # Panics
///
/// Panics if the composite corpus lacks any required matrix row.
fn composite_matrix_is_exhaustive() {
    use crate::composite::CompositeKind;
    let entries = composite_entries();
    let classify = |path: &str, lang: &str| {
        CompositeKind::from_discovered(path, Language::from_name(lang).unwrap())
    };
    let has = |needle: &str| entries.iter().any(|entry| entry.path == needle);
    assert!(has("svelte/Basic.svelte"), "svelte fixture required");
    assert!(has("svelte/Empty.svelte"), "empty svelte fixture required");
    assert!(has("vue/Basic.vue"), "vue fixture required");
    assert!(has("astro/Basic.astro"), "astro fixture required");
    assert!(has("liquid/Product.liquid"), "liquid fixture required");
    assert!(
        has("liquid/Broken.liquid"),
        "malformed-delimiter liquid fixture required"
    );
    assert!(
        has("liquid/Multibyte.liquid"),
        "multibyte coordinate fixture required"
    );
    assert!(
        has("liquid/Crlf.liquid"),
        "CRLF coordinate fixture required"
    );
    assert!(
        entries
            .iter()
            .any(|e| e.path == "liquid/templates/product.json"),
        "nested Shopify template JSON fixture required"
    );
    assert!(has("razor/Index.cshtml"), "razor cshtml fixture required");
    assert!(has("razor/Counter.razor"), "razor razor fixture required");
    assert!(
        has("cfml/UserService.cfc"),
        "tag-based CFML fixture required"
    );
    assert!(
        has("cfml/ModuleConfig.cfc"),
        "bare-script CFML fixture required"
    );
    assert!(has("cfml/Template.cfm"), "cfm template fixture required");
    assert!(has("xml/pom.xml"), "generic XML fixture required");
    assert!(has("xml/UserMapper.xml"), "MyBatis mapper fixture required");
    assert!(has("xml/Account.xml"), "iBatis sqlMap fixture required");
    assert!(has("play/conf/routes"), "Play routes fixture required");
    assert!(has("erlang/App.app.src"), "Erlang app fixture required");
    // Special-route neighbors must NOT classify as composites.
    assert_eq!(classify("config/app.json", "unknown"), None);
    assert_eq!(classify("locales/en.json", "unknown"), None);
    assert_eq!(classify("src/foo.src", "unknown"), None);
    assert_eq!(classify("routes.txt", "unknown"), None);
    // `.src` alone is not an Erlang app.
    assert_eq!(classify("src/foo.src", "unknown"), None);
    assert_eq!(
        classify("src/app.app.src", "erlang"),
        Some(CompositeKind::ErlangApp)
    );
}

#[test]
/// Verifies that composite special routes have no false positive neighbors preserves the frozen extraction contract.
///
/// `extract_from_source` must route Shopify `templates|sections/**/*.json`
/// to Liquid and reject `config/*.json`/`locales/*.json` (unknown); a
/// standalone `.src` file must not route to Erlang; `conf/routes` and
/// `*.routes` route to the empty Play/YAML path.
///
/// # Panics
///
/// Panics if routing behaves outside the frozen predicates.
fn composite_special_route_negatives() {
    let extractor = extractor();
    // Shopify template/section JSON routes to the Liquid file node.
    let shopify = extractor
        .extract_from_source(
            "templates/customers/login.json",
            r#"{"sections":{"a":{"type":"login-form"}}}"#,
        )
        .expect("shopify template json extracts");
    assert_eq!(shopify.nodes.len(), 1);
    assert_eq!(
        shopify.nodes[0].kind,
        bohmian_code_review_core::NodeKind::File
    );
    assert_eq!(shopify.nodes[0].language, Language::Liquid);
    // config/ and locales/ JSON are not Shopify and have no registered
    // extension → Unknown → typed rejection.
    for path in ["config/app.json", "locales/en.json"] {
        let error = extractor.extract_from_source(path, "{}").unwrap_err();
        assert!(
            matches!(error, ExtractionError::UnsupportedLanguage { .. })
                || matches!(error, ExtractionError::DisabledLanguage { .. }),
            "{path} must be rejected, got {error:?}"
        );
    }
    // `.src` alone is not an Erlang app file (unregistered extension).
    let error = extractor
        .extract_from_source("src/foo.src", "x")
        .unwrap_err();
    assert!(matches!(error, ExtractionError::UnsupportedLanguage { .. }));
    // Play routes (extensionless) extract to the empty file-level result.
    let routes = extractor
        .extract_from_source("conf/routes", "GET /  controllers.Home.index()\n")
        .expect("play routes extract");
    assert!(routes.nodes.is_empty());
    assert!(routes.references.is_empty());
}

