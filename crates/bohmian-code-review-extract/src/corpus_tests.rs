/// The composite manifest entries: `match` fixtures whose routed
/// language+path classifies into the closed [`CompositeKind`] set. Defer
/// entries (e.g. `cfscript/Broken.cfs`) stay with the native corpus's
/// defer-contract handling; the composite differential proves the routed
/// match output.
fn composite_entries() -> Vec<CorpusEntry> {
    load_manifest()
        .into_iter()
        .filter(|entry| {
            entry.expected == "match"
                && crate::composite::CompositeKind::from_discovered(&entry.path, language_of(entry))
                    .is_some()
        })
        .collect()
}

/// Extract a composite fixture through the full frozen dispatch
/// (`extractFromSource` semantics: route from the path, then native or
/// composite).
///
/// # Panics
///
/// Panics if the fixture cannot be read or extraction fails.
fn extract_composite(entry: &CorpusEntry) -> crate::result::ExtractionResult {
    let fixture = fixtures_dir().join(&entry.path);
    let bytes = std::fs::read(&fixture)
        .unwrap_or_else(|error| panic!("read composite fixture {}: {error}", fixture.display()));
    let source = String::from_utf8(bytes).expect("composite fixtures are UTF-8");
    extractor()
        .extract_from_source(&entry.path, &source)
        .unwrap_or_else(|error| panic!("extract_from_source {} failed: {error}", entry.path))
}

