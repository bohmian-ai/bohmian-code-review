#[test]
/// Verifies that extraction is deterministic byte identical preserves the frozen extraction contract.
///
/// # Panics
///
/// Panics if a selected fixture cannot be read, its relative path is invalid,
/// native extraction fails, either result cannot be serialized, or two runs
/// produce different serialized facts.
fn extraction_is_deterministic_byte_identical() {
    let entries = load_manifest();
    let extractor = extractor();
    for entry in entries
        .iter()
        .filter(|entry| entry.expected == "match" && language_of(entry).is_native())
    {
        let fixture = fixtures_dir().join(&entry.path);
        let bytes = std::fs::read(&fixture).expect("read fixture");
        let path = RelativePath::new(&entry.path).expect("valid fixture path");
        let source = SourceFile::new(&path, &bytes, language_of(entry));
        let first = extractor
            .extract(source)
            .expect("first extraction succeeds");
        let second = extractor
            .extract(source)
            .expect("second extraction succeeds");
        let first_json = serde_json::to_vec(&first).expect("serialize first");
        let second_json = serde_json::to_vec(&second).expect("serialize second");
        assert_eq!(
            first_json, second_json,
            "two extraction runs must produce byte-identical facts for {}",
            entry.path
        );
    }
}

